CREATE TABLE products (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(120)   NOT NULL,
    collection_name    VARCHAR(60)    NOT NULL,
    description        VARCHAR(2000)  NOT NULL,
    price              NUMERIC(12, 2) NOT NULL CHECK (price > 0),
    stock              INTEGER        NOT NULL CHECK (stock >= 0),
    case_material      VARCHAR(60)    NOT NULL,
    movement           VARCHAR(60)    NOT NULL,
    diameter_mm        INTEGER        NOT NULL,
    water_resistance_m INTEGER        NOT NULL,
    case_color         VARCHAR(7)     NOT NULL,
    dial_color         VARCHAR(7)     NOT NULL,
    strap_color        VARCHAR(7)     NOT NULL,
    accent_color       VARCHAR(7)     NOT NULL,
    customizable       BOOLEAN        NOT NULL,
    active             BOOLEAN        NOT NULL,
    version            BIGINT         NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_products_collection ON products (collection_name);
CREATE INDEX idx_products_active_price ON products (active, price);

CREATE TABLE customization_options (
    id          VARCHAR(40)    PRIMARY KEY,
    part        VARCHAR(10)    NOT NULL,
    name        VARCHAR(60)    NOT NULL,
    color_hex   VARCHAR(7)     NOT NULL,
    price_delta NUMERIC(12, 2) NOT NULL,
    sort_order  INTEGER        NOT NULL
);
